#!/usr/bin/env python3
"""Roll audit/results/*.json into audit/SUMMARY.md and audit/DEFECTS.md."""
import json, glob, os
from collections import Counter
R = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "audit")
rows, defects = [], []
for f in sorted(glob.glob(R + "/results/*.json")):
    reg = os.path.basename(f)[:-5]; d = json.load(open(f)); c = Counter(x["verdict"] for x in d)
    def rate(t, cl=None):
        s = [x for x in d if x.get("type") == t and (cl is None or x.get("claimed") == cl)]
        k = sum(x["verdict"] == "CONFIRMED" for x in s); r = sum(x["verdict"] == "REFUTED" for x in s)
        return f"{k}/{k+r}" if k + r else "-"
    wd = sum(1 for x in d if x.get("wrong_dollar") and x.get("bucket") == "top")
    rows.append(f"| {reg} | {len(d)} | {c['CONFIRMED']} | {c['REFUTED']} | {c['INCONCLUSIVE']} | {c['NOT_DONE']} | {rate('presence','Yes')} | {rate('presence','No')} | {wd} |")
    for x in d:
        if x["verdict"] == "REFUTED":
            defects.append(f"- [{reg}] idx {x['idx']} {x.get('type','')} {x.get('utility', x.get('state',''))} / {x.get('cell_or_program', x.get('cell',''))}: claimed `{str(x.get('claimed',''))[:80]}` -> {str(x.get('correct_value',''))[:140]} ({x.get('evidence_url','')})")
open(R + "/SUMMARY.md", "w").write("# Audit summary (generated by scripts/audit_rollup.py)\n\nBars: Yes>=95%, No>=90% (confirmed/(confirmed+refuted)), 0 wrong $ in top bucket. Inconclusive and NOT_DONE reported separately.\n\n| region | items | confirmed | refuted | inconclusive | not done | Yes | No | top wrong $ |\n|---|---|---|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
open(R + "/DEFECTS.md", "w").write("# Open audit defects (refuted items; see AUDIT_<region>.md for exact fixes)\n\n" + "\n".join(defects) + "\n")
print("\n".join(rows), len(defects))
